import { expect, test } from '@playwright/test';
import { createPost, fillOverLimit, goWrite, login } from './helpers';

test('Validation đăng nhập: trống, tối thiểu, tối đa và sai tài khoản', async ({ page }) => {
  await page.goto('/login');
  const submit = page.getByRole('button', { name: 'Đăng nhập', exact: true });
  await submit.click();
  await expect(page.locator('#username-error')).toContainText('Vui lòng nhập');
  await expect(page.locator('#password-error')).toContainText('Vui lòng nhập');
  await page.locator('#username').fill('a');
  await page.locator('#password').fill('123');
  await submit.click();
  await expect(page.locator('#username-error')).toContainText('ít nhất 3');
  await expect(page.locator('#password-error')).toContainText('ít nhất 6');
  await fillOverLimit(page, 'username', 30);
  await fillOverLimit(page, 'password', 64);
  await submit.click();
  await expect(page.locator('#username-error')).toContainText('vượt quá 30');
  await expect(page.locator('#password-error')).toContainText('vượt quá 64');
  await page.locator('#username').fill('admin');
  await page.locator('#password').fill('wrong-password');
  await submit.click();
  await expect(page.getByText('Tên đăng nhập hoặc mật khẩu không đúng.')).toBeVisible();
  await login(page);
  await expect(page).toHaveURL('/');
  await expect(page.getByRole('status').first()).toContainText('Đăng nhập thành công.');
});

test('Bảo vệ route, validation bài viết, lưu sau reload, hiện ở trang chủ và đăng xuất', async ({ page }) => {
  await goWrite(page);
  const submit = page.getByRole('button', { name: 'Đăng bài viết', exact: true });
  await submit.click();
  await expect(page.locator('#title-error')).toContainText('Vui lòng nhập');
  await expect(page.locator('#body-error')).toContainText('Vui lòng nhập');
  await page.locator('#title').fill('abc');
  await page.locator('#body').fill('quá ngắn');
  await submit.click();
  await expect(page.locator('#title-error')).toContainText('ít nhất 5');
  await expect(page.locator('#body-error')).toContainText('ít nhất 20');
  await fillOverLimit(page, 'title', 200);
  await fillOverLimit(page, 'body', 10000);
  await submit.click();
  await expect(page.locator('#title-error')).toContainText('vượt quá 200');
  await expect(page.locator('#body-error')).toContainText('vượt quá 10000');
  await createPost(page);
  const detailUrl = page.url();
  await page.reload();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Bài viết kiểm thử MiniBlog');
  await expect(page.getByRole('button', { name: 'Đăng xuất' })).toBeVisible();
  await page.getByRole('link', { name: 'Về danh sách bài viết' }).click();
  await expect(page.getByText('101 bài viết', { exact: true })).toBeVisible();
  await expect(page.locator('.post-card h3').first()).toHaveText('Bài viết kiểm thử MiniBlog');
  await page.getByRole('button', { name: 'Đăng xuất' }).click();
  await expect(page.getByText('Bạn đã đăng xuất.', { exact: true })).toBeVisible();
  await page.goto(detailUrl);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Bài viết kiểm thử MiniBlog');
  await expect(page.locator('.login-prompt')).toBeVisible();
  await page.goto('/write');
  await expect(page).toHaveURL(/\/login$/);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('miniblog.posts') || '[]') as unknown[]);
  expect(saved).toHaveLength(1);
});

test('Bình luận: yêu cầu đăng nhập, quay lại bài, validation và giữ sau reload', async ({ page }) => {
  await page.goto('/posts/1');
  await expect(page.locator('.comment')).toHaveCount(5);
  await page.locator('.login-prompt a').click();
  await login(page);
  await expect(page).toHaveURL(/\/posts\/1$/);
  const submit = page.getByRole('button', { name: 'Gửi bình luận' });
  await submit.click();
  await expect(page.locator('#comment-error')).toContainText('Vui lòng nhập');
  await page.locator('#comment').fill('ab');
  await submit.click();
  await expect(page.locator('#comment-error')).toContainText('ít nhất 3');
  await fillOverLimit(page, 'comment', 2000);
  await submit.click();
  await expect(page.locator('#comment-error')).toContainText('vượt quá 2000');
  await page.locator('#comment').fill('Bình luận kiểm thử được lưu trên trình duyệt.');
  await submit.click();
  await expect(page.getByText('Đã gửi bình luận.', { exact: true })).toBeVisible();
  await expect(page.locator('.comment')).toHaveCount(6);
  await page.reload();
  await expect(page.locator('.comment')).toHaveCount(6);
  await expect(page.locator('.comment').first()).toContainText('Bình luận kiểm thử');
  await page.goto('/posts/2');
  await expect(page.locator('.comment')).toHaveCount(5);
});
